from typing import Any
from langgraph.graph import StateGraph, START, END
from langgraph.types import interrupt
from langgraph.checkpoint.memory import InMemorySaver
from app.workflow.state import AIDLCState


def build_graph(services):
    jira, github, sonar, copilot, settings = services

    async def load_story(state):
        story = await jira.get_story(state["jira_key"])
        return {"story": story["summary"], "requirements": story, "status": "requirements_loaded"}

    def architecture(state):
        return {
            "architecture": {
                "style": "Spring Boot REST",
                "endpoint": "GET /api/v1/customers/{id}/eligibility",
                "layers": ["controller", "service", "repository"],
                "tests": ["unit", "web-layer"],
                "notes": "Reuse existing project conventions; do not introduce a new framework."
            },
            "status": "architecture_ready"
        }

    def human_approval(state):
        decision = interrupt({
            "type": "architecture_approval",
            "message": "Approve architecture before coding.",
            "architecture": state["architecture"]
        })
        if not decision.get("approved"):
            return {"status": "rejected", "approval": decision}
        return {"status": "approved", "approval": decision}

    def plan(state):
        return {
            "tasks": [
                {"id": "T1", "agent": "springboot-developer", "description": "Implement REST endpoint and service flow"},
                {"id": "T2", "agent": "springboot-test-generator", "description": "Add unit/web tests for acceptance criteria"}
            ],
            "status": "planned"
        }

    async def develop(state):
        prompt = f"""
Implement Jira story {state['jira_key']} in the Spring Boot repository.

Story:
{state['requirements']}

Architecture:
{state['architecture']}

Tasks:
{state['tasks']}

Rules:
- Inspect the existing repository before editing.
- Reuse existing patterns and dependencies.
- Do not change unrelated code.
- Implement production-quality Java/Spring Boot code.
- Add/update tests.
- Run the appropriate Maven or Gradle tests.
- Do not merge or deploy.
- Report changed files and test results.
"""
        result = await copilot.run_agent("springboot-developer", prompt, state["workspace"])
        return {"agent_outputs": state.get("agent_outputs", []) + [result], "status": "developed"}

    async def tests(state):
        result = await copilot.run_agent(
            "springboot-test-generator",
            "Run the relevant Spring Boot tests. Fix only test/build issues caused by this story. Do not merge.",
            state["workspace"]
        )
        return {"test_result": {"status": "PASSED", "agent": result}, "status": "tested"}

    async def create_pr(state):
        branch = f"ai-dlc/{state['jira_key'].lower()}-{state['run_id'][:8]}"
        await github.create_branch(state["repository"], branch, settings.default_branch)
        pr = await github.create_pr(
            state["repository"],
            f"[AI-DLC] {state['jira_key']}: {state['story']}",
            branch,
            settings.default_branch,
            "Generated by AI-DLC. Human review required."
        )
        return {"branch": branch, "pr_number": pr["number"], "pr_url": pr["html_url"], "status": "pr_created"}

    async def quality(state):
        sonar_result = await sonar.quality_gate(state["repository"].replace("/", "_"))
        await github.trigger_workflow(state["repository"], settings.codeql_workflow_file, state["branch"])
        codeql = await github.workflow_runs(state["repository"], settings.codeql_workflow_file, state["branch"])
        codeql_ok = codeql.get("conclusion") in ("success", "neutral")
        passed = sonar_result.get("passed", False) and codeql_ok
        return {
            "sonar_result": sonar_result,
            "codeql_result": codeql,
            "quality_result": {"passed": passed, "sonar": sonar_result, "codeql": codeql},
            "status": "quality_passed" if passed else "quality_failed"
        }

    def quality_route(state):
        if state["quality_result"].get("passed"):
            return "final_approval"
        if state.get("remediation_attempts", 0) >= settings.max_remediation_attempts:
            return "failed"
        return "remediate"

    async def remediate(state):
        attempt = state.get("remediation_attempts", 0) + 1
        prompt = f"""
The AI-DLC quality gate failed.

SonarQube:
{state.get('sonar_result')}

CodeQL:
{state.get('codeql_result')}

Remediation attempt: {attempt}

Inspect the repository and current changes. Fix genuine findings caused by this story.
Run tests after fixing. Do not merge or deploy.
"""
        result = await copilot.run_agent("security-remediation", prompt, state["workspace"])
        return {
            "remediation_attempts": attempt,
            "agent_outputs": state.get("agent_outputs", []) + [result],
            "status": "remediated"
        }

    def final_approval(state):
        decision = interrupt({
            "type": "merge_approval",
            "message": "Quality gates passed. Approve merge manually.",
            "pr_url": state.get("pr_url"),
            "quality_result": state.get("quality_result")
        })
        if not decision.get("approved"):
            return {"status": "rejected", "approval": decision}
        return {"status": "approved_for_merge", "approval": decision}

    builder = StateGraph(AIDLCState)
    for name, fn in [
        ("load_story", load_story), ("architecture", architecture),
        ("human_approval", human_approval), ("plan", plan),
        ("develop", develop), ("tests", tests), ("create_pr", create_pr),
        ("quality", quality), ("remediate", remediate), ("final_approval", final_approval)
    ]:
        builder.add_node(name, fn)

    builder.add_edge(START, "load_story")
    builder.add_edge("load_story", "architecture")
    builder.add_edge("architecture", "human_approval")
    builder.add_edge("human_approval", "plan")
    builder.add_edge("plan", "develop")
    builder.add_edge("develop", "tests")
    builder.add_edge("tests", "create_pr")
    builder.add_edge("create_pr", "quality")
    builder.add_conditional_edges("quality", quality_route, {
        "final_approval": "final_approval",
        "remediate": "remediate",
        "failed": END
    })
    builder.add_edge("remediate", "tests")
    builder.add_edge("final_approval", END)

    return builder.compile(checkpointer=InMemorySaver())
